/**
 * src/kernel/config/declaration_work.ts — عدُّ عملِ الإقلاع: حرَسُ الكلفة بما يُعَدّ لا بالساعة
 * المالك: القيّم على المستودع | المدخلات: نداءاتُ `noteBootWork` من مسار قراءة الإعلان
 * المخرجات: حصيلةُ عملٍ مقروءةٌ (`bootWork`) ورفضٌ عند تجاوز السقوف | التبعيات: types
 * الصلاحيات (RULE-004): يَعُدّ ولا يُصلح؛ ولا يُغيّر سقفًا من داخل ما يحرسه (RULE-005)
 * السجلات: قيدُ `boot_work_measured` في خاتمة الإقلاع | حالات الفشل: `BOOT_WORK_OVER_CEILING`
 * الوثيقة: docs/decisions/ADR-0037-boot-work-ceilings.md
 *   · القياسُ الخام: docs/audit/measurements/phase-39-T134.txt
 *
 * ثوابت هذه الوحدة:
 *
 *   1) **الزمنُ لا يُحرس بالساعة بل بعدِّ العمل** (T-134): زمنُ الجدار يختلف بآلةٍ وحمولةٍ
 *      وجارٍ في المُشغّل، فحاجزٌ عليه يسقط بريئًا أو يمرّ مذنبًا. وعددُ الملفات المقروءة
 *      والبايتات والتحليلات ومشيات المجلدات **عددٌ صحيحٌ لا يتغيّر بآلة** — فهو المحروس،
 *      والزمنُ يُقاس ويُقرأ **تاريخًا** كما أذن البند نفسُه.
 *
 *   2) **السقوفُ مشتقّةٌ من قياسٍ لا مُستحسَنة**: كلُّ سقفٍ هنا فوق المقيسِ في الجلسة 52 بمدًى
 *      معلنٍ في القياس الخام. ومن رفعه فعليه أن يُعلن ما تغيّر في العمل لا أن يُوسّع السقفَ
 *      ليمرّ بناؤه — **وسقفٌ يُرفع لتمرَّ دفعةٌ ليس سقفًا**.
 *
 *   3) **العدّادُ يُصفَّر في أوّلِ الإقلاع لا في آخره**: وحدةُ القياس **إقلاعٌ واحد**، فإقلاعان
 *      في عمليّةٍ واحدةٍ لا يتراكمان، وقراءةٌ خارج الإقلاع (أداةٌ أو اختبار) تُعَدّ ولا تُحرس
 *      — لأنّ الحرَسَ حرَسُ **بناءِ دولةٍ** لا حرَسُ كلِّ نداء.
 *
 *   4) **الحرَسُ يقع في مسارٍ مُقاسٍ لا في مسبارٍ يُنادى بيد** (نصُّ T-134): تُحرس الحصيلةُ
 *      في بوابةِ التكامل (`scripts/check_boot_work.sh`) على تهيئةِ المستودع الفعليّة، وتُدوَّن
 *      في دفتر الإقلاع — فحاجزٌ لا يُنادى في البوابة نصيحةٌ لا حرَس.
 *
 *   5) **لا يُحرس في الإقلاع نفسِه**: الإقلاعُ يَعُدّ ويُدوّن ولا يرفض بعدَدِ عمله؛ لأنّ دولةً
 *      تُرفض في مُشغِّل مستخدمٍ بسبب قراءةٍ زائدةٍ أسوأُ من دفعةٍ تُردّ في البوابة. والرفضُ
 *      موضعُه البوابةُ حيث يُقرأ ويُصلَح — وهذا انحرافٌ **مُعلنٌ** لا مسكوتٌ عنه.
 */
import { SovereignViolation } from '../types';

/** محاورُ العملِ المعدودةُ في الإقلاع — من زاد محورًا فليزد سقفَه معه */
export interface BootWork {
  /** عددُ ملفّات الإعلان المقروءة من القرص */
  file_reads: number;
  /** مجموعُ بايتاتها كما قِيست بـ`statSync` */
  bytes_read: number;
  /** عددُ نداءات التحليل (`parseSimpleYaml`) */
  parse_calls: number;
  /** عددُ مشيات مجلدات الإعلان (حصرًا أو حرَسًا) */
  dir_walks: number;
  /** عددُ مدخلات المجلدات التي نُظر فيها أثناء المشي */
  dir_entries: number;
  /** عددُ القراءات التي كفتها ذاكرةُ الإقلاع (T-139) — عملٌ لم يُصرف على القرص */
  memo_hits: number;
  /** عددُ العُقد التي زارها عدُّ العُقد */
  node_visits: number;
}

/**
 * سقوفُ عملِ الإقلاع — مُجمَّدةٌ ومشتقّةٌ من قياسٍ لا من استحسان، **ومُضيَّقةٌ كلَّما نقص العمل**.
 * المقيسُ في الجلسة 53 بعد ذاكرةِ قراءةِ الإقلاع (T-139) على تهيئة المستودع — وهو عددٌ
 * **يتكرّر حرفًا** في كلِّ إقلاع: `file_reads: 27` · `memo_hits: 82` · `bytes_read: 76749`
 * · `parse_calls: 27` · `dir_walks: 87` · `dir_entries: 2084` · `node_visits: 846`.
 * وكان قبلها (الجلسة 52): 109 · — · 192264 · 109 · 87 · 2084 · 2744.
 * والسقوفُ فوق المقيس بمدًى معلن (×1.4 تقريبًا، والبايتاتُ 131072 = **نصفَ** سقفِ مجموعِ
 * الإعلان) — تسمح بنموِّ الإعلان ولا تسمح بتضاعفِ **العمل** على إعلانٍ ثابت.
 * **ولا يُوسَّع سقفٌ ليمرّ بناءٌ**: من نقص عملُه ضيّق سقفَه في الدفعة نفسِها كما ضُيِّق هنا،
 * ومن زاده أعلن ما تغيّر. ولو كان هذا الحرَسُ قائمًا في الجلسة 51 لأسقط دفعةَ T-133
 * نفسَها: أضافت **86 مشيةَ مجلدٍ** حيث كانت واحدةً.
 */
export const BOOT_WORK_CEILINGS: Readonly<BootWork> = Object.freeze({
  file_reads: 40,
  memo_hits: 120,
  bytes_read: 131072,
  parse_calls: 40,
  dir_walks: 120,
  dir_entries: 3000,
  node_visits: 1280,
});

const ZERO: BootWork = {
  file_reads: 0,
  memo_hits: 0,
  bytes_read: 0,
  parse_calls: 0,
  dir_walks: 0,
  dir_entries: 0,
  node_visits: 0,
};

let counters: BootWork = { ...ZERO };

/** يُصفّر العدّاد — يُنادى في أوّلِ الإقلاع، فوحدةُ القياس إقلاعٌ واحد (الثابت 3) */
export function resetBootWork(): void {
  counters = { ...ZERO };
}

/**
 * يزيد محورًا من محاور العمل.
 * @param axis المحور المعدود
 * @param amount الزيادة (افتراضُها واحد)
 */
export function noteBootWork(axis: keyof BootWork, amount = 1): void {
  counters[axis] += amount;
}

/** يُعيد حصيلةَ العمل نسخةً — فلا يُعدَّل العدّادُ من قارئه */
export function bootWork(): BootWork {
  return { ...counters };
}

/**
 * يحرس حصيلةَ العمل بالسقوف المعلنة.
 * @param work الحصيلةُ المحروسة — افتراضُها حصيلةُ هذه العمليّة
 * @returns المحاورُ المفحوصةُ بعددها — يُقرأ ولا يُستنتج
 * @throws SovereignViolation عند أوّلِ محورٍ فوق سقفه (`BOOT_WORK_OVER_CEILING`)
 */
export function guardBootWork(work: BootWork = bootWork()): number {
  const axes = Object.keys(BOOT_WORK_CEILINGS) as (keyof BootWork)[];
  for (const axis of axes) {
    const measured = work[axis];
    const ceiling = BOOT_WORK_CEILINGS[axis];
    if (measured > ceiling) {
      throw new SovereignViolation(
        `عملُ الإقلاع فوق سقفه المعلن — ${axis} بلغ: ${measured}/${ceiling}. `
        + 'الزمنُ لا يُحرس بالساعة بل بعدِّ العمل (T-134)، فمن زاد العملَ فليُعلن ما تغيّر '
        + 'لا أن يُوسّع السقفَ ليمرّ بناؤه',
        'BOOT_WORK_OVER_CEILING',
      );
    }
  }
  return axes.length;
}
