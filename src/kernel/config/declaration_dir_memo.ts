/**
 * src/kernel/config/declaration_dir_memo.ts — بصمةُ قياسِ المجلد في الإقلاع (البند T-140)
 * المالك: القيّم على المستودع | المدخلات: مجلدٌ · قياسُه (بايتاتٌ وملفاتٌ) · بصماتُ مجلداته
 * المخرجات: قياسٌ محفوظٌ يُعاد استخدامُه، أو لا شيءَ فيُمشى المجلدُ من جديد
 * التبعيات: لا شيء (وحدةٌ بلا تبعيّة: لا تقرأ قرصًا ولا تمشي مجلدًا ولا ترمي)
 * الصلاحيات (RULE-004): تخزّن وتُرجع وتَنسى؛ **لا تحرس سقفًا ولا تُلغي حرَسًا ولا تُقرِّر**
 * السجلات: لا قيدَ لها وحدَها — أثرُها محورا `dir_walks` و`dir_reuses` في `boot_work_measured`
 * حالات الفشل: لا ترمي. وأيُّ شكٍّ في الطزاجة ⇒ لا شيء ⇒ مشيٌ كاملٌ وقياسٌ من القرص
 * الوثيقة: docs/decisions/ADR-0039-declaration-directory-memo.md
 *   · القياسُ الخام: docs/audit/measurements/phase-39-T140.txt
 *
 * ثوابت هذه الوحدة:
 *
 *   1) **البصمةُ تشمل كلَّ مجلدٍ مُشِيَ فيه لا المجلدَ الأعلى وحدَه**: زمنُ تعديلِ مجلدٍ يتغيّر
 *      بإضافةِ مدخلٍ أو حذفِه أو إعادةِ تسميته **في هذا المجلد وحدَه**؛ فملفٌّ منفوخٌ يُدَسّ في
 *      `config/nested/` لا يُحرّك زمنَ `config/`. ولذلك يُخزَّن مع القياس زمنُ **كلِّ** مجلدٍ
 *      مُشِيَ فيه، ولا يُعاد استخدامُ القياس إلّا إذا طابقت البصماتُ كلُّها.
 *
 *   2) **القياسُ يُخزَّن مع أحجامِ ملفاته لا مجموعًا مجرَّدًا**: زمنُ المجلد لا يتغيّر إذا نُفخ
 *      ملفٌّ **في مكانه** (كتابةٌ فوق ملفٍّ قائم). فيُخزَّن حجمُ كلِّ مسارٍ كما قيس، ليُقارَن
 *      بالحجم الذي يراه المحمّلُ عند قراءته — ومن اختلف حجمُه أُنسي قياسُ مجلدِه كلِّه.
 *
 *   3) **الشكُّ يُنسي ولا يُخمِّن**: أيُّ نقصٍ أو اختلافٍ — بصمةٌ غائبةٌ، زمنٌ مختلفٌ، حجمٌ لم
 *      يطابق — يُلغي القياسَ المحفوظَ كلَّه لذلك المجلد. فالوحدةُ لا تُصلح قياسًا جزئيًّا ولا
 *      تُرقّعه: المشيُ الكاملُ هو الحدُّ الأدنى عند أوّلِ شكّ.
 *
 *   4) **ذاكرةُ إقلاعٍ لا ذاكرةُ عمليّة**: تُنسى في أوّلِ كلِّ تركيبِ سيادةٍ مع ذاكرةِ القراءة
 *      (T-139). فكلُّ إقلاعٍ يقيس مجلدَ إعلانِه بنفسه، ويبقى عدُّ العمل (T-134) **ثابتًا بين
 *      إقلاعَين** فيصلح عقدًا لا حظًّا.
 *
 *   5) **لا تُلغي حرَسًا**: سقفُ بايتات المجلد يُفحص عند كلِّ نداءٍ على القياس — محفوظًا كان
 *      أو مقيسًا الآن — ويرمي برمزِه `CONFIG_DECLARATION_DIR_BYTES_OVER_CEILING`. والوحدةُ
 *      توفّر **مشيًا** ولا توفّر **حكمًا**؛ ولا يُخزَّن قياسٌ فوق السقف أصلًا.
 *
 *   6) **حدُّ ما تعرفه معلنٌ لا مسكوتٌ عنه**: يبقى خارجَ مداها نفخُ ملفٍّ **في مكانه لا
 *      يقرؤه أحدٌ في هذا الإقلاع** — لا زمنَ مجلدٍ يتغيّر ولا قارئَ يكشفُ الحجم. وهذا انحرافٌ
 *      **مُعلنٌ ومقيسٌ** في ADR-0039، لا فجوةٌ اكتُشفت بعد الدفع.
 *
 *   7) **وقد أُغلق حدُّ الثابت 6 في الإقلاع نفسِه** (البند T-141): لا بفحصٍ عند كلِّ نداءٍ —
 *      فقيس أنّ إعادةَ إحصاءِ الأحجام في كلِّ إعادةِ استخدامٍ تُعيد **3.17ms** إلى إقلاعٍ
 *      وسيطُه 7.62ms (+42%) — بل بـ**إعادةِ تحقّقٍ واحدةٍ في خاتمة الإقلاع** تُعيد قياسَ كلِّ
 *      مجلدٍ حُفظ قياسُه، بثمنٍ مقيسٍ **0.138ms** (1.8%). ولذلك تُعلن هذه الوحدةُ **أسماءَ**
 *      المجلدات المحفوظة (`directoryMeasureNames`): من لا يُعلن ما حفظه لا يُعاد التحقّقُ منه.
 */

/** قياسُ مجلدٍ محفوظٌ: مجموعُه وعددُ ملفاته، وبصماتُ مجلداته، وأحجامُ مساراته */
export type DirectoryMeasure = {
  /** مجموعُ بايتات ملفات الإعلان تحت المجلد كما قيس بالمشي */
  readonly bytes: number;
  /** عددُ ملفات الإعلان التي دخلت المجموع */
  readonly files: number;
  /** مجلدٌ ⇒ زمنُ تعديله بالنانو ثانية — كلُّ مجلدٍ مُشِيَ فيه، لا الأعلى وحدَه (ثابت 1) */
  readonly stamps: ReadonlyMap<string, bigint>;
  /** مسارٌ ⇒ حجمُه كما قيس — لتُكشف كتابةٌ فوق ملفٍّ قائم (ثابت 2) */
  readonly sizes: ReadonlyMap<string, number>;
};

const MEASURES = new Map<string, DirectoryMeasure>();

/**
 * القياسُ المحفوظُ لمجلدٍ **بلا فحصِ طزاجة** — الفحصُ مسؤوليّةُ من يمشي المجلدَ ويقرأ
 * الأزمنة، لأنّ هذه الوحدةَ لا تلمس قرصًا (ثابتُ التبعيّات).
 * @param dir مجلدُ الإعلان
 */
export function storedDirectoryMeasure(dir: string): DirectoryMeasure | undefined {
  return MEASURES.get(dir);
}

/**
 * يحفظ قياسَ مجلدٍ — لا يُنادى إلّا بقياسٍ **تحت السقف** وبصماتٍ قُرئت في المشية نفسِها.
 * @param dir مجلدُ الإعلان
 * @param measure القياسُ وبصماتُه وأحجامُه
 */
export function memoizeDirectoryMeasure(dir: string, measure: DirectoryMeasure): void {
  MEASURES.set(dir, measure);
}

/**
 * يُنسي قياسَ مجلدٍ إن كان حجمُ مسارٍ فيه قد تغيّر عمّا قيس — جوابُ الثابت 2: من كتب فوق
 * ملفٍّ قائمٍ لم يُحرّك زمنَ المجلد، فيَكشفُه أوّلُ قارئٍ للملف.
 * @param dir مجلدُ الملفّ
 * @param path مسارُ الملفِّ الذي يُقرأ الآن
 * @param bytes حجمُه الآن كما قيس قبل قراءته
 * @returns هل أُنسي القياسُ؟ — يُقرأ في الاختبارات ولا يُستنتج
 */
export function forgetDirectoryMeasureIfFileChanged(
  dir: string,
  path: string,
  bytes: number,
): boolean {
  const measure = MEASURES.get(dir);
  if (!measure) return false;
  const known = measure.sizes.get(path);
  if (known === bytes) return false;
  MEASURES.delete(dir);
  return true;
}

/**
 * يُنسى القياسُ — مجلدًا بعينه أو كلَّه. يُنادى في أوّلِ كلِّ إقلاعٍ (ثابت 4) وفي الاختبارات.
 * @param dir مجلدٌ بعينه، أو لا شيءَ فيُنسى الكلّ
 */
export function resetDirectoryMeasures(dir?: string): void {
  if (dir === undefined) MEASURES.clear();
  else MEASURES.delete(dir);
}

/**
 * أسماءُ المجلدات المحفوظِ قياسُها الآن — بها تُعاد خاتمةُ الإقلاع التحقّقَ من كلِّ ما
 * اتُّكئ عليه (ثابت 7). نسخةٌ لا مرجعٌ: من قرأ لا يُغيّر ما حُفظ.
 */
export function directoryMeasureNames(): string[] {
  return [...MEASURES.keys()];
}

/** عددُ المجلدات المحفوظِ قياسُها الآن — يُقرأ في الاختبارات والمقاييس، لا يُستنتج */
export function directoryMeasureCount(): number {
  return MEASURES.size;
}
