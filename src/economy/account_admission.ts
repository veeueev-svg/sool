/**
 * src/economy/account_admission.ts — شرطُ قبولِ الحساب: حجّةٌ واحدةٌ لا نسختان (المرحلة 25 · T-54)
 * المالك: وزارة المالية — والشرطُ حجّةٌ عليها لا لها
 * القاعدة الحاكمة RULE-000: أي تعديل هنا يُوثَّق في PROGRESS.md مع تقرير اختبار
 * المدخلات: وصفُ حسابٍ كما يأتي من بابِ الفتحِ أو من قيدِ يوميّةٍ مُستعاد
 * المخرجات: سببُ الردِّ نصًّا، أو `null` إن كان الحسابُ مقبولًا
 * التبعيات: لا شيء — وحدةٌ نقيّةٌ بلا حالةٍ ولا أثرٍ جانبيّ، ليشترك فيها البابان بلا دورة
 * الصلاحيات: تحكم ولا تُدخِل — الإدخالُ لصاحبِ الدفتر
 * السجلات: لا سجلَّ هنا؛ المُنادي هو من يُسجّل رفضَه أو يرمي فشلَه المغلق
 * ثوابت هذه الوحدة:
 *   1) **بابانِ يُدخلانِ حسابًا وشرطٌ واحدٌ يحكمهما**: `Ledger.openAccount` و`Ledger.restore`.
 *      وكان الشرطُ مكتوبًا في الأوّلِ وحدَه، فمرّ من الثاني حسابٌ يرفضه الأوّل، وخرجت إليه
 *      250,000 وحدةً **والميزانُ متوازن** (docs/audit/measurements/phase-25-T54.txt §3).
 *   2) **النوعُ يُحرَس في التشغيل لا في الترجمة**: الحسابُ يأتي من يوميّةٍ نصًّا، والمُصنِّفُ
 *      لا يقف على ما يُقرأ من قرصٍ — فالتعدادُ مجمَّدٌ ويُفحَص عضويّتُه.
 *   3) **تحكم ولا تُعاقب**: تُرجع سببًا يُقرأ، ويبقى لكلِّ بابٍ شكلُ فشلِه — رفضٌ مسجَّلٌ في
 *      بابِ الفتح، وفشلٌ مغلقٌ في بابِ الإرجاع.
 * حالات الفشل (كلها مغلقة): معرّفٌ بلا «:» ⇒ ردّ؛ اسمٌ أقصرُ من ثلاثةٍ بعد التشذيب ⇒ ردّ؛
 *   نوعٌ خارجَ `ACCOUNT_KINDS` ⇒ ردّ
 * اختبار القبول: tests/economy/treasury.test.ts (T54-01…T54-06)
 * الوثيقة المرتبطة: docs/test-reports/phase-25-T54.md
 */
import type { AccountKind } from './ledger';

/** أنواعُ الحسابِ المقبولةُ في التشغيل — النوعُ يأتي من يوميّةٍ نصًّا فلا يحرسه المُصنِّف وحدَه */
export const ACCOUNT_KINDS: readonly AccountKind[] = Object.freeze(
  ['asset', 'liability', 'equity', 'revenue', 'expense'] as const,
);

/**
 * T-54: **شرطُ قبولِ الحسابِ حجّةٌ واحدةٌ لا نسختان**.
 * كان الشرطُ مكتوبًا داخل `openAccount` وحدَه، و`restore` بابٌ ثانٍ لا يمرّ به فيحرس
 * **العددَ** (`RECOVERY_LEDGER_ACCOUNT_CAP`) ولا يحرس **شرطَ القبول** — فقيدُ يوميّةٍ
 * واحدٌ يصنع حسابًا يرفضه بابُ الفتح، ثمّ يُصرَف إليه، والميزانُ يبقى متوازنًا فلا
 * ترفعه مطابقةٌ حسابيّة (القياسُ الحرفيّ: docs/audit/measurements/phase-25-T54.txt §3).
 * فصار الشرطُ دالّةً واحدةً يشترك فيها البابان: يرفض بها `openAccount` رفضًا مسجَّلًا،
 * ويفشل بها `restore` فشلًا مغلقًا كأخيه.
 * @returns سببُ الردِّ نصًّا، أو `null` إن كان الحسابُ مقبولًا.
 */
export function accountAdmissionFault(
  account: { readonly accountId: string; readonly kind: string; readonly name: string },
): string | null {
  if (typeof account.accountId !== 'string' || !account.accountId.includes(':')) {
    return 'معرّف حساب غير صالح: يجب أن يكون <نوع>:<اسم>';
  }
  if (typeof account.name !== 'string' || account.name.trim().length < 3) {
    return 'لا حساب بلا اسم معلن';
  }
  if (!ACCOUNT_KINDS.includes(account.kind as AccountKind)) {
    return `نوع حساب غير معلن: ${String(account.kind)} — المعلن: ${ACCOUNT_KINDS.join(' · ')}`;
  }
  return null;
}
