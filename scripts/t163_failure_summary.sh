#!/usr/bin/env bash
# scripts/t163_failure_summary.sh — T-163 (W-2026-021)
# خطوةٌ تشخيصيةٌ تُخرجُ أسطرَ الأحكامِ الساقطةِ إلى ملخّصِ التشغيل ($GITHUB_STEP_SUMMARY)
# فتُقرأُ من صفحةِ التشغيلِ دون مضيفِ السجلِّ المحجوب.
#
# لا تُغيّرُ الحكمَ: تُشغَّلُ بـ`if: failure()` فقط بعدَ سقوطِ خطوةٍ سابقةٍ (الوظيفةُ حمراءُ
# أصلًا)، ورمزُ خروجِها 0 دائمًا — فلا تُسوّدُ أخضرَ ولا تُخضِرُ أحمرَ. ولا إعادةَ محاولةٍ
# ولا ابتلاعَ فشلٍ. وتقرأُ dist/.tests.tap (الذي يكتبهُ node --test) فتستخرجُ أسطرَ `not ok`.
set -u

# بلا ملخّصِ تشغيلٍ (محلّيًّا) — لا شيءَ يُخرَج، والخروجُ 0.
[ -z "${GITHUB_STEP_SUMMARY:-}" ] && exit 0
# بلا ملفِّ نتائج (سقوطٌ قبلَ الاختبارات) — لا شيءَ يُخرَج.
[ -f dist/.tests.tap ] || exit 0

{
  echo "## فشلُ اختباراتِ القبولِ — الأحكامُ الساقطةُ (T-163)"
  echo ""
  echo '```'
  grep -E '^not ok' dist/.tests.tap | head -100 || true
  echo '```'
} >> "$GITHUB_STEP_SUMMARY"

exit 0
