#!/usr/bin/env bash
# scripts/check_absolute_paths.sh — منع عودة المسار المطلق إلى الشفرة والاختبارات والأدوات (البند T-118)
# المالك: القيّم على المستودع | الوثيقة المرتبطة: docs/test-reports/phase-39.md §13
# المدخلات: أشجار src/ وtests/ وscripts/ | المخرجات: 0 إذا لا مسار مطلق، و1 مع بيان كل سطر مخالف
# حالات الفشل: أي مسار يبدأ بجذر جهازٍ بعينه (/home/ أو /Users/ أو /root/) ⇒ فشل مغلق
#
# ثوابت هذه الأداة:
#   1) **المستودع لا يعرف مسار جهازه.** مسارٌ مطلق يعمل عند كاتبه ويسقط عند كل من بعده،
#      وسقوطُه في بوابة CI هو عين ما حدث في البند T-117: حاجزٌ معلن لم يُشغَّل قطّ.
#   2) **الفحص يقرأ ولا يُصلح** (RULE-004): يسمّي الملف والسطر ويسقط، ولا يعدّل شفرة.
#   3) **لا استثناء صامت.** كل استثناءٍ لازمٍ يُعلن في هذا الملف بسببه، لا في سطر أوامر عابر.
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# الجذور الممنوعة: مسارات منزل جهازٍ بعينه. لا يُضاف إليها استثناء بلا سبب مكتوب.
PATTERN='(/home/[A-Za-z0-9._-]+/|/Users/[A-Za-z0-9._-]+/|/root/)'

echo "فحص المسارات المطلقة في src/ وtests/ وscripts/ (البند T-118)"
# الاستثناء الوحيد المعلن: هذا الملف نفسه — فيه نصُّ النمط الممنوع، ولا يمكن أن يفحص نفسه.
matches="$(grep -rnE "$PATTERN" src tests scripts \
  --exclude=check_absolute_paths.sh 2>/dev/null || true)"

if [ -n "$matches" ]; then
  echo "✗ مسار مطلق مكتوب — يعمل عند كاتبه ويسقط عند غيره:"
  echo "$matches"
  echo "البديل المعلن: resolveConfigDir() للتهيئة، وimport.meta.url أو __dirname لجذر المستودع."
  exit 1
fi

echo "✓ لا مسار مطلق في الشفرة ولا في الاختبارات ولا في الأدوات"
exit 0
