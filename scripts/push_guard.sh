#!/usr/bin/env bash
# scripts/push_guard.sh — الدفعُ فعلٌ محكوم: لا يُدفع إلّا ما قُرئ حكمُه (T-151)
#
# العلّةُ التي وُلد منها هذا الحارس، مقيسةً في الجلسة 62:
#   التشغيلة 84 سقطت في الخطوة 19 «بوابةُ ضبطِ العمل». **والحاجزُ لم يخطئ**: شُغِّل محلّيًّا
#   وأصدر ✗ قبل الدفع بثوانٍ — لكنّه شُغِّل في نداءٍ واحدٍ مع الدفع، فمضى الدفعُ ولم يُقرأ
#   الحكم. فالعلّةُ في **طريقِ الدفع**: طريقٌ بلا باب، والنيّةُ وحدَها كانت هي الحرس.
#   ونيّةٌ تُنسى؛ والإجراءُ لا يُنسى (RULE-001: الفعلُ لا الاسم).
#
# القراراتُ المعلنة:
#   1) **الحارسُ يقرأ الأحكامَ ولا يستنسخها**: لا يُعيد منطقَ حاجزٍ، بل يُشغّل الحواجزَ
#      المُعلنةَ في جدولِه ويقرأ رمزَ خروجِ كلٍّ منها. فمن أراد حكمًا جديدًا زاد صفًّا.
#   2) **ما لا يُشغَّل يُعلَن**: `npm test` والبناءُ خارجَ الحارسِ بثمنٍ مقيس، فيُطبع سطرُ
#      «لا يُشغّله هذا الحارس» صراحةً — فلا يوهم أنّه السلسلةُ كلُّها.
#   3) **الشجرةُ غيرُ النظيفةِ تردُّ الدفع**: أداةُ الدفعِ تقرأ الملفّاتَ من شجرةِ العمل، فلو
#      كانت فيها تعديلاتٌ غيرُ ملتزَمةٍ لدُفع محتوًى **لم يحكم عليه حاجزٌ قطُّ** (قيس بتجربةٍ
#      محلّيّة: اختلافُ sha256 بين شجرةِ العملِ وHEAD لملفٍّ مُعدَّلٍ بلا التزام).
#   4) **الحصرُ الأعمى ردٌّ لا نجاح** (درسُ `[CI-05]`): صفرُ حواجزَ شُغِّلت = لا حكمَ، لا خضرة.
#   5) كلُّ حكمٍ يُطبع برمزٍ لاتينيٍّ ثابتٍ `[PG-NN]` قبل نصِّه العربيّ — عقدًا بين الحارسِ
#      واختبارِه، فلا ينكسر الاختبارُ على تنقيحِ صياغة.
#
# الاستخدام: bash scripts/push_guard.sh
#   SOOL_GUARD_ROOT=<مجلد>   يُغيّر الجذرَ المحروس (تُحرَّف نسخةٌ لا أصل — درسُ W-2026-004)
#   SOOL_GUARD_GATES=<جدول>  انحرافٌ **معلن** للاختبار وحدَه: يُبدل جدولَ الحواجزِ بأسطر
#                            «الاسم|الأمر»، فتُقاس أحكامُ الحارسِ بلا تشغيلِ السلسلةِ الحقيقيّة
# النتيجة: 0 إذا كان الدفعُ مأذونًا، و1 مع بيانِ الحكمِ الذي يمنعه
#
# ولا يدخل هذا الحارسُ في `npm run verify`: هو **يُشغّل** تلك السلسلة، فإدخالُه فيها يُشغّلها
# مرّتَين ويجعل `check_ci_gates.sh` يطلب له خطوةً في الدمج — وحكمُ الدمجِ على الالتزامةِ لا
# على طريقِ دفعِها. فبقاؤه خارجَها قرارٌ مقيسٌ لا سهو.

set -u

ROOT="${SOOL_GUARD_ROOT:-.}"

echo "حارسُ الدفع: لا يُدفع إلّا ما قُرئ حكمُه (T-151)"

fail=0
ran=0

# ── [PG-06] مدخلٌ غائب: ما ليس مستودعًا لا يُحكم عليه ────────────────────────────
if [ ! -d "$ROOT/.git" ]; then
  echo "✗ [PG-06] لا مستودعَ في «$ROOT»: لا مجلَّدَ .git — وحارسٌ بلا مدخلٍ لا يأذن، ولا يقول «لا مانع»"
  exit 1
fi

# ── [PG-01] شجرةُ العملِ نظيفة: المدفوعُ يُقرأ من الملفّات لا من الالتزامة ────────
dirty="$(git -C "$ROOT" status --porcelain 2>/dev/null)"
if [ -n "$dirty" ]; then
  echo "✗ [PG-01] شجرةُ العملِ ليست نظيفة — وأداةُ الدفعِ تقرأ الملفّات، فالمدفوعُ حينئذٍ ليس ما حكم عليه حاجز:"
  printf '%s\n' "$dirty" | sed 's/^/      /'
  fail=1
fi

# ── [PG-02] رسالةُ الالتزامِ مستوفيةٌ للصيغةِ الإلزاميّة ومِذيالِ البند ──────────
msg="$(git -C "$ROOT" log -1 --pretty=%B 2>/dev/null || true)"
if [ -z "$msg" ]; then
  echo "✗ [PG-02] لا رسالةَ التزامٍ تُقرأ في «$ROOT» — والدفعُ بلا رسالةٍ دفعٌ بلا أثرٍ يُراجَع"
  fail=1
else
  missing=""
  for field in "تم:" "لم يتم:" "التالي:" "الاختبارات:" "التوثيق:"; do
    printf '%s' "$msg" | grep -q "^$field" || missing="$missing $field"
  done
  # والمِذيالُ يُقاس **في موضعِه**: آخرُ سطرٍ غيرِ فارغ. وطفرةٌ خصوميّةٌ نجت أوّلًا لأنّ الفحصَ
  # كان يقبله في أيِّ موضع، ومِذيالٌ مدفونٌ في الجسدِ لا يقرأه git ولا قارئُ السجل (A1).
  last_line="$(printf '%s' "$msg" | grep -v '^[[:space:]]*$' | tail -1)"
  if ! printf '%s' "$last_line" | grep -qE '^Work: W-[0-9]{4}-[0-9]{3}$'; then
    missing="$missing Work:(في-آخرِ-سطر)"
  fi
  if [ -n "$missing" ]; then
    echo "✗ [PG-02] رسالةُ الالتزامِ ناقصةٌ — الحقولُ الغائبة:$missing (والصيغةُ في docs/work/WORK_CONTROL.md)"
    fail=1
  fi
fi

# ── [PG-07] الفَرقُ غيرُ فارغ: التزامةٌ بلا مسارٍ لا شيءَ فيها يُراجَع ───────────
changed="$(git -C "$ROOT" diff --name-only HEAD~1 HEAD 2>/dev/null || true)"
if [ -z "$changed" ]; then
  echo "✗ [PG-07] لا مسارَ في فَرقِ HEAD~1..HEAD — فلا شيءَ يُدفع، ولا يُدفع فراغٌ ليُقال دُفع"
  fail=1
fi

# ── جدولُ الحواجزِ المحروسِ بها: الاسم|الأمر ─────────────────────────────────────
# قرارُ الاختيار مقيسٌ لا مزاجيّ: هذه هي حواجزُ السلسلةِ كلُّها **إلّا** الاختباراتَ والبناء،
# ومجموعُ أزمنتِها مقيسٌ نحو 3.7 ثانية (أثقلُها check_module_size.sh بـ1.46) — ثمنٌ يُحتمل
# قبل كلِّ دفعة. وحاجزا البناءِ (`dist/`) يُشغَّلان إن وُجد أثرُهما، وإلّا رُدَّ الدفعُ
# بـ[PG-05] ولا يُفترض نجاحُهما.
DEFAULT_GATES=$(cat <<'TABLE'
ضبط العمل|node scripts/check_work.mjs
مدقّق التوثيق|bash scripts/check_documentation.sh HEAD~1
حاجز الإعلان|bash scripts/check_declaration.sh
الأرقام المولَّدة|bash scripts/check_generated_numbers.sh
بوابة الدمج مقابل السلسلة|bash scripts/check_ci_gates.sh
المسارات المطلقة|bash scripts/check_absolute_paths.sh
حدود حجم الوحدة|bash scripts/check_module_size.sh
قرّاء الإعلان|bash scripts/check_config_readers.sh
حالات معايير القبول|bash scripts/check_criteria_status.sh
التعدادات المغلقة|bash scripts/check_closed_enums.sh
عمل الإقلاع|bash scripts/check_boot_work.sh
سلامة سجل التدقيق|node dist/scripts/verify_audit_chain.js
حاجز الحصر|node dist/scripts/check_confinement.js
TABLE
)
GATES="${SOOL_GUARD_GATES:-$DEFAULT_GATES}"

# ── تشغيلُ الحواجزِ وقراءةُ أحكامِها — والقراءةُ هي كلُّ المسألة ─────────────────
while IFS='|' read -r name cmd; do
  [ -z "${name:-}" ] && continue
  # [PG-05] ملفُّ الحاجزِ المُعلَنِ مفقود: لا يُفترض نجاحُ ما لا يوجد
  target="$(printf '%s' "$cmd" | awk '{for(i=1;i<=NF;i++) if ($i ~ /\.(sh|mjs|js|ts)$/) {print $i; exit}}')"
  if [ -n "$target" ] && [ ! -f "$ROOT/$target" ]; then
    echo "✗ [PG-05] حاجزٌ مُعلَنٌ لا يوجد ملفُّه: «$target» ($name) — والغائبُ يُردُّ به الدفعُ ولا يُتخطّى بصمت"
    fail=1
    continue
  fi
  out="$(cd "$ROOT" && eval "$cmd" 2>&1)"
  code=$?
  ran=$((ran + 1))
  if [ "$code" -ne 0 ]; then
    echo "✗ [PG-03] حاجزٌ ردَّ ($name) برمزِ خروج $code — وهذا الحكمُ هو ما كان يُنتَج ولا يُقرأ:"
    printf '%s\n' "$out" | tail -3 | sed 's/^/      /'
    fail=1
  else
    echo "  ✓ $name"
  fi
done <<< "$GATES"

# ── [PG-04] الحصرُ الأعمى: صفرُ حواجزَ شُغِّلت ليس خضرةً ─────────────────────────
if [ "$ran" -eq 0 ]; then
  echo "✗ [PG-04] لم يُشغَّل حاجزٌ واحد — وصفرُ أحكامٍ ليس إذنًا بالدفع (درسُ [CI-05])"
  fail=1
fi

# ورقمُ التأكيداتِ يُقرأ من version.json لا يُكتب باليد: رقمٌ جامدٌ يشيخ في أوّلِ إضافة (قيس: قال 2114 والمقيسُ 2133).
tests_total="$(sed -n 's/.*"total": \([0-9]*\).*/\1/p' "$ROOT/version.json" 2>/dev/null | head -1)"
[ -n "$tests_total" ] || tests_total="غيرُ مقروءٍ من version.json"
echo "ℹ لا يُشغّله هذا الحارس: npm test ($tests_total تأكيدًا) والبناءُ — ثمنُهما زمنٌ لا يُحتمل قبل كلِّ دفعة،"
echo "  وهما الخطوتان 5 و6 من بوابةِ الدمج. فهذا الحارسُ بابٌ على الدفعِ لا بديلٌ عن السلسلة."

if [ "$fail" -ne 0 ]; then
  echo "✗ حارسُ الدفع يمنع: الحكمُ أعلاه قُرئ ولم يُطوَ — فصحِّح ثمّ ادفع (T-151)"
  exit 1
fi

echo "✓ حارسُ الدفع يأذن: $ran حاجزًا شُغِّلت وقُرئت أحكامُها، والشجرةُ نظيفةٌ والرسالةُ مستوفيةٌ — والإذنُ قراءةٌ لا نيّة"
exit 0
